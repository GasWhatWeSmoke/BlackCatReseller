// Dump config/template.db's schema to config/schema-manifest.json.
//
// The packaged app has no Prisma CLI (it is a devDependency) and therefore no
// `prisma db push`. It copies template.db on first run and then never touches the
// schema again — so a tester who installs v1.2, uses it, and updates to v1.3 keeps a
// v1.2 database and every query touching a new column fails. This manifest is what
// lets the runtime migrator (scripts/schema-sync.mjs) know what the schema SHOULD be
// without shipping the CLI.
//
// Runs as part of `npm run db:template`, so it can never lag the template it describes.
import { DatabaseSync } from "node:sqlite";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const templatePath = path.join(root, "config", "template.db");
const outPath = path.join(root, "config", "schema-manifest.json");

/** Read a SQLite file's tables + indexes into a plain, diffable object. */
export function readSchema(dbPath) {
  const db = new DatabaseSync(dbPath, { readOnly: true });
  try {
    const tables = {};
    const rows = db
      .prepare("SELECT name, sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name")
      .all();
    for (const { name, sql } of rows) {
      const columns = db.prepare(`PRAGMA table_info(${JSON.stringify(name)})`).all().map((c) => ({
        name: c.name,
        type: c.type,
        notnull: c.notnull === 1,
        // SQLite hands defaults back as literal SQL text ("0", "'Unknown'", "CURRENT_TIMESTAMP").
        // Kept verbatim so the migrator can paste it straight into an ALTER statement.
        dflt: c.dflt_value == null ? null : String(c.dflt_value),
        pk: c.pk > 0,
      }));
      tables[name] = { sql, columns };
    }
    const indexes = db
      .prepare("SELECT name, sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL ORDER BY name")
      .all()
      .map((r) => ({ name: r.name, sql: r.sql }));
    return { tables, indexes };
  } finally {
    db.close();
  }
}

function main() {
  if (!fs.existsSync(templatePath)) {
    console.error(`config/template.db is missing — run \`npm run db:template\` first.`);
    process.exit(1);
  }
  const schema = readSchema(templatePath);
  const manifest = {
    _doc:
      "Generated by scripts/schema-manifest.mjs from config/template.db. Consumed by " +
      "scripts/schema-sync.mjs at app startup to bring an EXISTING user database up to " +
      "the shipped schema (additive only). Do not hand-edit — regenerate with `npm run db:template`.",
    tableCount: Object.keys(schema.tables).length,
    ...schema,
  };
  fs.writeFileSync(outPath, `${JSON.stringify(manifest, null, 1)}\n`, "utf8");
  const columns = Object.values(schema.tables).reduce((n, t) => n + t.columns.length, 0);
  console.log(`schema-manifest: ${manifest.tableCount} table(s), ${columns} column(s) -> config/schema-manifest.json`);
}

if (import.meta.url === `file://${process.argv[1].replace(/\\/g, "/")}` ||
    process.argv[1]?.endsWith("schema-manifest.mjs")) {
  main();
}
